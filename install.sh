#!/bin/sh
# Small bundled manager; proxy cores download from official URLs.
set -eu
umask 077
if [ "$(id -u)" -ne 0 ]; then
  echo "请使用 root 或 sudo sh install.sh" >&2; exit 1
fi
if [ "$(uname -s)" != Linux ] || [ ! -d /run/systemd/system ]; then
  echo "需要 Debian 12+ / Ubuntu 22.04+，以及 systemd" >&2; exit 1
fi
if ! command -v apt-get >/dev/null 2>&1; then
  echo "当前安装器支持 Debian / Ubuntu" >&2; exit 1
fi
case "$(uname -m)" in x86_64|aarch64) ;; *) echo "仅支持 amd64/arm64" >&2; exit 1 ;; esac
. /etc/os-release
os_major=$(echo "$VERSION_ID" | cut -d . -f 1)
case "$ID" in
  debian) [ "$os_major" -ge 12 ] || { echo "需要 Debian 12+"; exit 1; } ;;
  ubuntu) [ "$os_major" -ge 22 ] || { echo "需要 Ubuntu 22.04+"; exit 1; } ;;
  *) echo "当前支持 Debian 12+ / Ubuntu 22.04+"; exit 1 ;;
esac
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y --no-install-recommends python3 ca-certificates curl openssl socat iproute2 kmod qrencode
task_tmp=$(mktemp -d)
trap 'rm -rf -- "$task_tmp"' EXIT HUP INT TERM
awk 'found { print } /^# __V2_PAYLOAD__$/ { found=1 }' "$0" | base64 -d > "$task_tmp/manager.tar.gz"
echo '394eee4d533194b6e3f713dd3bcd1ccc1c6211efa5466f5f1ab02f305493aa74' " $task_tmp/manager.tar.gz" | sha256sum -c -
tar -xzf "$task_tmp/manager.tar.gz" -C "$task_tmp"
python3 -m py_compile "$task_tmp"/v2/*.py
install -d -m 755 /usr/local/lib/v2
install -d -m 755 /usr/local/bin
rm -rf -- /usr/local/lib/v2/v2
cp -R "$task_tmp/v2" /usr/local/lib/v2/
chmod -R a+rX /usr/local/lib/v2/v2
cat > /usr/local/bin/v2 <<'LAUNCHER'
#!/bin/sh
export PYTHONPATH=/usr/local/lib/v2
export PYTHONUTF8=1
exec python3 -m v2 "$@"
LAUNCHER
chmod 755 /usr/local/bin/v2
if [ ! -e /usr/local/bin/v2ray ] && ! command -v v2ray >/dev/null 2>&1; then
  ln -s /usr/local/bin/v2 /usr/local/bin/v2ray
fi
/usr/local/bin/v2 install "$@"
exit 0
